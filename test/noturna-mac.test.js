function escreverControle(w, c = {}) {
  const todos = { NODE_REAL: process.execPath, PYTHON_REAL, ROOT, ...c };
  const linhas = Object.entries(todos).map(([k, v]) => `export ${k}='${String(v).replace(/'/g, "'\\''")}'`);
  fs.writeFileSync(path.join(w.stubs, "controle.env"), linhas.join("\n") + "\n");
}

const lerSe = (p) => (fs.existsSync(p) ? fs.readFileSync(p, "utf8") : "");

function logDatado(w) {
  if (!fs.existsSync(w.logs)) return "";
  const arquivos = fs.readdirSync(w.logs).filter((f) => f.endsWith(".log")).sort();
  return arquivos.length ? fs.readFileSync(path.join(w.logs, arquivos[arquivos.length - 1]), "utf8") : "";
}

function estadoDe(w) {
  const p = path.join(w.estado, "ultima-rodada.json");
  return fs.existsSync(p) ? JSON.parse(fs.readFileSync(p, "utf8")) : null;
}

/** The node calls the stub recorded, one object per line: { tipo, linha }. */
function chamadasNode(w) {
  return lerSe(path.join(w.chamadas, "node.log")).split("\n").filter(Boolean).map((linha) => ({ tipo: linha.split(" ")[0], linha }));
}

function rodar(w, modo, controle = {}, env = {}) {
  dentro(w, w.lancador, w.home);
  escreverControle(w, controle);
  const t0 = Date.now();
  return new Promise((resolve) => {
    const filho = spawn(w.lancador, [modo], { env: ambiente(w, env), stdio: ["ignore", "pipe", "pipe"] });
    let stdout = "", stderr = "";
    filho.stdout.on("data", (d) => { stdout += d; });
    filho.stderr.on("data", (d) => { stderr += d; });
    const relogio = setTimeout(() => filho.kill("SIGKILL"), 240000);
    filho.on("close", (status) => {
      clearTimeout(relogio);
      resolve({ status, stdout, stderr, log: logDatado(w), estado: estadoDe(w), chamadas: chamadasNode(w), ms: Date.now() - t0 });
    });
  });
}

