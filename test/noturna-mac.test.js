/** A temporary folder with a bare "origin" (a copy of the seeded one), the stubs, an empty HOME, and (unless told otherwise) the dedicated clone, launcher and plist made by the real installer. */
function mundo({ instalar = true } = {}) {
  const tmp = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "noturna-")));
  const w = { tmp, home: path.join(tmp, "home"), origem: path.join(tmp, "origem.git"), stubs: path.join(tmp, "stubs"), tmpdir: path.join(tmp, "tmpdir"), gitconfig: path.join(tmp, "gitconfig") };
  w.clone = path.join(w.home, "Claude", "mood-engine-noturna");
  w.lancador = path.join(w.home, "bin", "noturna-mood-engine");
  w.estado = path.join(w.home, "Library", "Application Support", "noturna-mood-engine");
  w.logs = path.join(w.home, "Library", "Logs", "noturna-mood-engine");
  w.chamadas = path.join(w.stubs, "chamadas");
  for (const d of [w.home, w.tmpdir]) fs.mkdirSync(d, { recursive: true });
  fs.writeFileSync(w.gitconfig, "");
  spawnSync("cp", ["-R", STUBS, w.stubs]);
  for (const f of fs.readdirSync(w.stubs)) if (fs.statSync(path.join(w.stubs, f)).isFile()) fs.chmodSync(path.join(w.stubs, f), 0o755);
  spawnSync("cp", ["-R", molde().origem, w.origem]);
  w.limpar = () => { matarRestos(w); fs.rmSync(tmp, { recursive: true, force: true }); };
  if (instalar) {
    const r = instalador(w, []);
    assert.equal(r.status, 0, `installer: ${r.stderr}${r.stdout}`);
  }
  return w;
}

/** The start time of a process as the lock records it: in UTC, whatever zone this machine is in (re-verification of 21/10/2026, finding MEDIUM 1: the launcher and the night must write and read it in the same zone). */
function inicioDe(pid) {
  return spawnSync("ps", ["-o", "lstart=", "-p", String(pid)], { encoding: "utf8", env: { ...process.env, TZ: "UTC" } }).stdout.trim();
}

/** Ends whatever a failed assertion left running under the lock (the launcher, the night's group, the group of the command under a limit) before the folder they work in is removed. Found in the
 * mutation run of 21/10/2026 (round 3): a test that failed early removed the world under a live launcher, which then held the whole test run for ever. A process is touched only when its start time
 * is the one the lock recorded (the rule of the launcher itself), so a pid that has been reused is left alone; after a night that ended normally the lock is gone and this does nothing. */
function matarRestos(w) {
  const arquivo = (nome) => (fs.existsSync(path.join(w.estado, "trava", nome)) ? fs.readFileSync(path.join(w.estado, "trava", nome), "utf8") : "");
  const linhas = [...arquivo("dono").split("\n").filter(Boolean).map((l, i) => ({ alvo: i === 0 ? 1 : -1, c: l.split("\t") })), { alvo: -1, c: arquivo("limite.pgid").trim().split("\t") }];
  for (const { alvo, c } of linhas.reverse()) {
    const pid = Number(c[0]);
    if (!Number.isInteger(pid) || pid <= 1 || !c[1] || inicioDe(pid) !== c[1]) continue;
    try { process.kill(alvo * pid, "SIGKILL"); } catch { /* gone */ }
  }
}

/** Every path handed to a script must be inside the temporary folder. */
function dentro(w, ...caminhos) {
  for (const c of caminhos) if (!path.resolve(c).startsWith(w.tmp + path.sep) && path.resolve(c) !== w.tmp) throw new Error(`path outside the temporary folder: ${c}`);
}

